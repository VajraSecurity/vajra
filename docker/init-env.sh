#!/usr/bin/env bash
# Creates .env for docker-compose.yml with random secrets. Safe to re-run: it never
# overwrites an existing .env.
#
#   ./docker/init-env.sh [public-host]
#
# public-host is the name or IP that browsers and agents use to reach this machine
# (default: this machine's first IP address, or localhost if none is found). The agent
# downloads and the web console are built for this address.
set -euo pipefail
cd "$(dirname "$0")/.."

# The script install (./install.sh) uses the same ports (console, 4000, 1234): not both on one machine.
if systemctl is-active --quiet vajra-backend 2>/dev/null || systemctl is-active --quiet vajra_server 2>/dev/null; then
  echo "WARNING: the script install of Vajra is running on this machine and uses the same ports as Docker." >&2
  echo "         Remove it first with ./uninstall.sh, or the Docker containers will fail to start." >&2
fi

# Remember which public images were already on this machine, so docker/cleanup.sh leaves them.
if [ ! -f .docker-images-before ] && command -v docker >/dev/null 2>&1; then
  for img in postgres:16 redis:7-alpine apache/kafka:3.8.0 alpine:3.20; do
    docker image inspect "$img" >/dev/null 2>&1 && echo "$img"
  done > .docker-images-before || true
fi

if [ -f .env ]; then
  echo ".env already exists, not changing it."
  exit 0
fi

rand() { openssl rand -hex 24; }
HOST="${1:-$(hostname -I 2>/dev/null | awk '{print $1}')}"
HOST="${HOST:-localhost}"
umask 077
cat > .env <<ENV
# Generated by docker/init-env.sh. See .env.example for what each value does.
PUBLIC_HOST=$HOST
DB_PASSWORD=$(rand)
SSL_PASSWORD=$(rand)
ENROLLMENT_SECRET=$(rand)
ACCESS_JWT_SECRET=$(rand)
REFRESH_JWT_SECRET=$(rand)
NESSUS_ENCRYPTION_KEY=$(rand)
ENV
echo "Wrote .env (PUBLIC_HOST=$HOST)."
